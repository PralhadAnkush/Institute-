/**
 * Dynamically generates a brand-new, randomized GCC-TBC passage every time it is called.
 * Passages are calibrated to 40-65 words so they fit cleanly inside the screen viewport.
 */
export function generateDynamicGccPassage(
  language: LanguageMode,
  benchmarkWpm: 30 | 40,
  runNumber: number
): GccTbcPassage {
  const pool = UNLIMITED_PASSAGE_POOL[language];

  // Pick a fresh unique passage every time
  const randomOffset = Math.floor(Math.random() * pool.length);
  const selectedIdx = (runNumber + randomOffset) % pool.length;
  const passageText = pool[selectedIdx];
  const wordCount = passageText.split(/\s+/).length;

  return {
    id: `gcc-dyn-${language}-${benchmarkWpm}-${Date.now()}-${runNumber}`,
    language,
    category: benchmarkWpm === 30 ? 'GCC-TBC 30 WPM' : 'GCC-TBC 40 WPM',
    benchmarkWpm,
    durationMinutes: 7,
    totalMarks: 40,
    passingMarks: 16,
    targetWords: wordCount,
    title:
      language === 'mr'
        ? `GCC-TBC मराठी ${benchmarkWpm === 30 ? '३०' : '४०'} WPM परिच्छेद #${runNumber}`
        : `GCC-TBC English ${benchmarkWpm} WPM Passage #${runNumber}`,
    paperCode:
      language === 'mr'
        ? `MSCE पुणे · GCC-TBC मराठी ${benchmarkWpm} WPM · वेळ: ७ मिनिटे · एकूण गुण: ४०`
        : `MSCE Pune · GCC-TBC English ${benchmarkWpm} WPM · Time: 7 Minutes · Total Marks: 40`,
    text: passageText,
  };
}
