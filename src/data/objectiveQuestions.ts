export function generateRandomObjectiveSet(count = 25): ObjectiveQuestion[] {
  const copy = [...GCC_TBC_OBJECTIVE_QUESTIONS];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const temp = copy[i];
    copy[i] = copy[j];
    copy[j] = temp;
  }
  return copy.slice(0, Math.min(count, copy.length));
}

